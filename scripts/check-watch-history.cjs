const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const ts = require('typescript');
const source = fs.readFileSync(require('node:path').join(__dirname, '../src/lib/watch-history.ts'), 'utf8');
const output = ts.transpileModule(source, { compilerOptions: { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 } }).outputText;
const values = new Map();
const context = { exports: {}, Date, Event, window: { dispatchEvent() {} }, localStorage: { getItem: key => values.get(key) ?? null, setItem: (key, value) => values.set(key, value) } };
vm.runInNewContext(output, context);
const { saveWatchProgress, readWatchHistory, findWatchProgress, WATCH_HISTORY_KEY } = context.exports;
const item = { id: 101, title: 'Example', poster_url: 'https://example.com/cover.jpg' };
saveWatchProgress(item, 1, 120, 1200);
assert.equal(readWatchHistory().length, 1);
assert.equal(findWatchProgress(101, 1).currentTime, 120);
saveWatchProgress(item, 1, 250, 1200);
assert.equal(readWatchHistory().length, 1);
assert.equal(findWatchProgress(101, 1).currentTime, 250);
saveWatchProgress(item, 2, 180, 1200);
assert.equal(readWatchHistory().length, 1);
assert.equal(findWatchProgress(101, 1), undefined);
assert.equal(findWatchProgress(101, 2).currentTime, 180);
saveWatchProgress(item, 2, 1150, 1200);
assert.equal(readWatchHistory().length, 0);
saveWatchProgress(item, 3, 2, 1200);
saveWatchProgress(item, 3, 20, Number.NaN);
assert.equal(readWatchHistory().length, 0);
values.set(WATCH_HISTORY_KEY, '{invalid json');
assert.equal(readWatchHistory().length, 0);
values.set(WATCH_HISTORY_KEY, '[null, {"title":"incomplete"}]');
assert.equal(readWatchHistory().length, 0);
context.localStorage.setItem = () => { throw new Error('Storage unavailable'); };
assert.doesNotThrow(() => saveWatchProgress(item, 1, 120, 1200));
console.log('Watch history checks passed: save, update, episode switch, completion, invalid data, unavailable storage.');
